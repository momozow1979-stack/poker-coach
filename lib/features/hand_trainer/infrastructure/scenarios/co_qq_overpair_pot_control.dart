/// 中級 / OOP / ドライ。
///
/// CO のオーバーペア QQ を、フロップは価値ベット、ターンの K でポット管理、
/// リバーは値段を見てブラフキャッチ、という「オーバーペアの下げ方」を学ぶ。
/// ポット: open 2.5 → BTN call（6.5）→ flop bet 3（12.5）→ turn チェック回し →
/// river はチェックに 8 ベットされて必要勝率 約28%。
final TrainerScenario coQqOverpairPotControl = buildScenario(
  id: 'tr012',
  title: 'COのQQ、ターンでKが落ちたら',
  goal:
      'オーバーペアを「いつ価値ベットし、いつポットを抑えるか」を、'
      'スケアカードの扱いとブラフキャッチまで通して判断できるようになります。',
  difficulty: TrainerDifficulty.intermediate,
  hero: Position.co,
  villain: Position.btn,
  heroCards: 'Qh Qd',
  villainProfile: VillainStyles.reg,
  boardStyle: BoardStyle.dry,
  spots: [
    // ---------------------------------------------------------- プリフロップ --
    buildSpot(
      street: Street.preflop,
      potBb: 1.5,
      stackBb: 100,
      history: ['UTG・HJ フォールド', 'あなた（CO）の番です'],
      question: 'まだ誰も参加していません。QQ でどうしますか？',
      hint: 'QQ は169種の中でも上位のハンド。CO は後ろに BTN とブラインドしか残っていません。',
      terms: [TrainerTerms.openRaise, TrainerTerms.limp],
      options: [
        best(
          'レイズ 2.5BB',
          reason:
              'QQ は最上位クラスのハンドです。CO は後ろが3人だけの好位置なので、'
              '標準サイズのオープンで主導権を握り、広い相手のコールから価値を取りにいきます。',
          ifChanged:
              '後ろに極端に降りにくい相手が並んでいるなら、価値を厚く取るため'
              'サイズを少し上げる調整もあります。',
        ),
        bad(
          'コール（リンプ）',
          reason:
              '最上位クラスのハンドをリンプで入るのは、主導権を捨てるうえに'
              '多人数を安く呼び込み、せっかくの強さを活かせません。',
          ifChanged:
              '複数人がすでにリンプしている特殊な卓なら、後追いのリンプが成立する'
              'こともありますが、通常はレイズに統一するほうが強い方針です。',
        ),
        bad(
          'フォールド',
          endsHand: true,
          reason:
              'QQ を降りる理由はまったくありません。ここで降りると、'
              'そもそも参加できるハンドがほとんど無くなってしまいます。',
          ifChanged: '降りが正解になるのは、これよりはるかに弱いハンドのときだけです。',
        ),
        bad(
          'レイズ 6BB',
          reason:
              'サイズを上げすぎると、払ってくれる弱いハンドが降り、'
              '残ってコールするのは強い手に寄ります。相手の平均が強くなり逆効果です。',
          ifChanged:
              '相手が「小さいレイズには全部コールする」と分かっているなら、'
              '強い手だけサイズを上げる調整はありますが、全ハンドで上げると読まれます。',
        ),
      ],
      outcome: 'BTN がコール。ブラインドはフォールド。ポットは 6.5BB になります。',
    ),

    // -------------------------------------------------------------- フロップ --
    buildSpot(
      street: Street.flop,
      newCards: '8c 5d 2h',
      potBb: 6.5,
      stackBb: 97.5,
      history: ['あなた（CO）から先に action です'],
      question: '低くてバラけたボードです。QQ はオーバーペア。どうしますか？',
      hint:
          'このボードで、あなたのQQに勝っている手はどれくらいありますか。'
          'ドローも少ないボードです。',
      terms: [TrainerTerms.cbet, TrainerTerms.valueBet, TrainerTerms.dryBoard],
      options: [
        best(
          'ベット 3BB（約1/2ポット）',
          reason:
              'QQ はこのボードのほぼ全てに勝っているオーバーペアです。'
              '相手の小さいペアやハイカード、ガットショットから払わせるため、'
              '中庸なサイズで価値を取りにいきます。',
          ifChanged:
              'ボードに A や K が絡んでいたら、相手のトップペアが増えるので'
              'サイズや頻度を落とします。ここは怖いカードが無いので強く打てます。',
        ),
        ok(
          'チェック',
          reason:
              '一度チェックして相手のブラフを誘う作戦も成立はします。'
              'ただしドローが少ないボードでは、素直に価値ベットしたほうが'
              'ポットを育てられて分かりやすく得です。',
          ifChanged:
              '自分のレンジに弱い手が多く、チェックで守りたい場面なら'
              'チェックの価値が上がります。QQ 単体では打つほうが優れます。',
        ),
        bad(
          'ベット 6BB（約1ポット）',
          reason:
              '大きく打つと、払ってくれる弱いペアやハイカードが降りてしまいます。'
              '降ろしたい相手はもともと当たっておらず、得られるものが小さくなります。',
          ifChanged:
              'ボードがウェットでドローに値段を与えたくないなら、大きいサイズが機能します。'
              'ドライボードでは中庸〜小さめが基本です。',
        ),
      ],
      outcome: 'BTN がコール。ポットは 12.5BB になります。',
    ),

    // ---------------------------------------------------------------- ターン --
    buildSpot(
      street: Street.turn,
      newCards: 'Ks',
      potBb: 12.5,
      stackBb: 94.5,
      history: ['あなた（CO）から先に action です'],
      question: 'K が落ちました。オーバーペアだった QQ は、いま何番目でしょう。どうしますか？',
      hint:
          'K はあなたを強くしていません。逆に、相手が持っていた'
          'Kx（AK・KQ・KJ）を強くしました。',
      terms: [TrainerTerms.scareCard, TrainerTerms.spr, TrainerTerms.potOdds],
      options: [
        best(
          'チェック',
          reason:
              'K はあなたの QQ をオーバーペアから「Kより下のペア」に格下げしました。'
              '打っても払ってくれるのは K のペア以上に寄り、あなたが負けている手が中心です。'
              'ここはポットを抑え、安く見せてブラフや弱い手のベットを受ける番です。',
          ifChanged:
              '相手が K を持っていないと強く読める（極端にタイトでフロップで降りるはず）'
              'なら、薄く1発打つ価値も出ます。読みが変われば結論も変わります。',
        ),
        ok(
          'ベット 4BB（小さく）',
          reason:
              'まだ相手の小さいペアやドローから薄く取れる、という考え方も成立します。'
              'ただし K で相手の強い手が増えているので、リスクの割に見返りは小さめです。',
          ifChanged: '相手がコール頻度の高いステーションなら、薄いベットの価値が上がります。',
        ),
        bad(
          'ベット 9BB（約3/4ポット）',
          reason:
              'K が出た後に大きく打つと、あなたが勝っている弱い手は降り、'
              '残るのは K のペアやセットなど、あなたが負けている手ばかりになります。',
          ifChanged:
              'あなたが実際にセットや AK を持っているなら、大きいサイズが正解に近づきます。'
              '同じボードでも手の強さでサイズは変わります。',
        ),
      ],
      outcome: 'BTN もチェック。ポットは 12.5BB のままリバーへ進みます。',
    ),

    // ---------------------------------------------------------------- リバー --
    buildSpot(
      street: Street.river,
      newCards: '4c',
      potBb: 20.5,
      stackBb: 94.5,
      toCallBb: 8,
      history: ['あなたのチェックに、BTN が 8BB ベット（約2/3ポット）'],
      question: 'リバーはブランク。相手から先にベットが来ました。どうしますか？',
      hint:
          '相手の手を「あなたが負けている手」だけで想像していませんか。'
          '空振りしたドローやブラフも相手のレンジには入ります。',
      terms: [
        TrainerTerms.potOdds,
        TrainerTerms.requiredEquity,
        TrainerTerms.bluff,
      ],
      options: [
        best(
          'コール（8BB）',
          reason:
              '8BB 払って最終ポット 28.5BB を取りにいく形で、必要勝率は約28%です。'
              'QQ は K を引けなかったブラフや、あなたより弱いペア（8x・小ペア）に勝てます。'
              'ターンでポットを抑えたぶん、リバーはこの値段でブラフキャッチに回れます。',
          ifChanged:
              '相手が「リバーで打つのは本物だけ」というナリ気味のタイプなら、'
              'フォールドが正解に近づきます。相手のブラフ頻度で結論が変わります。',
        ),
        ok(
          'フォールド',
          endsHand: true,
          reason:
              '相手が受け身でブラフをほとんどしないタイプなら、K以下のペアで'
              '払い続けるのは損なので、降りる判断も成立します。',
          ifChanged:
              '相手が積極的で3ストリート目に空振りを打ってくるタイプなら、'
              'この価格ではコールが正解です。',
        ),
        bad(
          'レイズ 24BB',
          reason:
              'K 以下のペアでレイズしても、払ってくれるのはあなたが負けている手ばかりで、'
              'ブラフに対しては相手を降ろすだけです。価値もブラフも成立しにくい選択です。',
          ifChanged: 'あなたがセットなど本当に強い手なら、レイズでバリューを伸ばせます。',
        ),
      ],
    ),
  ],
  takeaway:
      'このハンドの軸は「オーバーペアは、盤面が変わると順位が下がる」ことです。\n\n'
      'フロップは怖いカードが無くQQが最上位だったので、素直に価値ベットしました。\n'
      'ターンの K は自分を強くせず相手の Kx を強くしたので、ポットを抑えました（ポット管理）。\n'
      'リバーは自分から打つ側ではなく、必要勝率 約28%を見てブラフキャッチする側に回りました。\n\n'
      '「強いオーバーペアだから最後まで押す」ではありません。'
      '出たカードが誰を助けたかを毎回見て、価値ベットとポット管理を切り替えるのがコツです。',
);
