      question: 'A ハイのドライボードでトップペアです。どうしますか？',
      hint:
          'このボードで A を多く持っているのは、3ベットした側とコールした側の'
          'どちらでしょうか。ドローもほとんどありません。',
      terms: [
        TrainerTerms.cbet,
        TrainerTerms.rangeAdvantage,
        TrainerTerms.dryBoard,
      ],
      options: [
        bad(
          'チェック',
          reason:
              'トップペア・トップキッカーは、この場面で一番払ってもらえる側の手です。'
