        ),
        bad(
          'ベット 17BB（約3/4ポット）',
          reason:
              '大きく打つと、払ってくれるはずの弱いハンド（K高・Q高・小ペア）が先に降ります。'
              '降ろしたい相手はもともと当たっていないので、得られるものが小さいスポットです。',
          ifChanged:
              '同じ A72 でも2枚が同スートでフラッシュドローがあるなら、'
              '大きいサイズが機能します。守るべきものがあるかでサイズは変わります。',
        ),
      ],
      outcome: 'BTN がコール。ポットは 37BB になります。',
    ),

