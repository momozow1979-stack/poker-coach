              'ハーフサイズなら払ってくれる手を残しつつ十分に取りにいけます。',
          ifChanged:
              '相手がターンで急に受けを強めるタイプなら、サイズを落とすか'
              'チェックに切り替えます。相手の反応でサイズは調整します。',
        ),
        bad(
          'オールイン（82BB）',
          reason:
              'ポット 37BB に対してスタック 82BB を一気に賭ける形です。'
              'トップペア1枚で、勝っている相手を全部降ろし、負けている相手にだけ'
              'コールされる賭け方になり、割に合いません。',
          ifChanged:
              'スタックが浅い（残り20BB程度）なら、オールインは現実的な選択になります。'
              'SPR が変われば同じ手でも答えは変わります。',
        ),
      ],
      outcome: 'BTN がコール。ポットは 73BB になります。',
    ),

    // ---------------------------------------------------------------- リバー --
