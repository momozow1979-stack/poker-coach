          ifChanged:
              '相手が「打たれると降りるが、チェックには自分から打つ」タイプなら、'
              'あえてチェックして打たせる調整もあります。',
        ),
        best(
          'ベット 7BB（約1/3ポット）',
          reason:
              '3ベットした側は AK・AQ・AA など A を強く持ちやすく、レンジ全体で有利です。'
