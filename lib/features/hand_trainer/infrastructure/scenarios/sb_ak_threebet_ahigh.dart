              'SB はポストフロップで先に動く不利な席なので、コールで受けるより'
              '3ベットして主導権を握り、BB のスクイーズも防ぐほうが戦いやすくなります。',
          ifChanged:
              '相手が UTG の激タイトなオープンなら、AKs でもコールを混ぜる価値が出ます。'
              '相手のレンジが狭いほど、3ベットで降ろせる弱いハンドが減るためです。',
        ),
        ok(
          'コール',
          reason:
              'AKs でフラットして、相手の弱いハンドを残す作戦も一応成立します。'
