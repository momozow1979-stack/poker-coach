      street: Street.river,
      newCards: 'Th',
      potBb: 97,
      stackBb: 64,
      toCallBb: 24,
      history: ['あなたのチェックに、BTN が 24BB ベット（約1/3ポット）'],
      question: '相手から先にベットが来ました。トップペアで、どうしますか？',
      hint:
          'まず「いくら払って、勝てば最終的にいくら取れるか」を見ます。'
          '画面の必要勝率が、そのまま判断の基準です。',
      terms: [TrainerTerms.potOdds, TrainerTerms.requiredEquity],
      options: [
        best(
          'コール（24BB）',
          reason:
              '24BB 払って最終ポット 121BB を取りにいく形なので、必要勝率は約20%です。'
              '5回に1回勝てれば元が取れます。AK のトップペアは、相手の空振りドロー'
