  static Quiz _q({
    required String id,
    required QuizDifficulty difficulty,
    Street street = Street.preflop,
    required Position hero,
    Position? villain,
    required String heroCards,
    String board = '',
    double stackBb = 100,
    double potBb = 1.5,
    TableType tableType = TableType.sixMax,
    String villainProfile = VillainProfile.reg,
    List<String> history = const [],
    required String question,
    required List<String> choices,
    required int correctIndex,
    required String shortReason,
    required String gtoView,
    required String practicalView,
    required String commonMistake,
    String? relatedRangeSpotId,

    /// true にすると、各選択肢のラベルから [inferActionType] でアクション種別を
    /// 推測して付与する。ポジション問題は「Fold/Call/Raise/All-in」のような
    /// 定型のアクション選択肢と、ポジション理論そのものを問う概念的な選択肢
    /// （日本語の説明文）が混在するため、ファイル全体には一括で有効化せず、
    /// 選択肢が明確にアクション語だけで構成されている設問だけで個別に true を渡す。
    bool tagActionTypes = false,
  }) {
    return buildQuiz(
      id: id,
      category: QuizCategory.position,
      difficulty: difficulty,
      street: street,
      hero: hero,
      villain: villain,
      heroCards: heroCards,
      board: board,
      stackBb: stackBb,
      potBb: potBb,
      tableType: tableType,
      villainProfile: villainProfile,
      history: history,
      question: question,
      choices: choices,
      correctIndex: correctIndex,
      shortReason: shortReason,
      gtoView: gtoView,
      practicalView: practicalView,
      commonMistake: commonMistake,
      relatedRangeSpotId: relatedRangeSpotId,
      tagActionTypes: tagActionTypes,
    );
  }

